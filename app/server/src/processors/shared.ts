import type { AssLine, LyricBuilderAssOptions } from 'jaraoke-shared/types';

const DEFAULT_SCREEN = {
  width: 1280,
  height: 720,
};

const padTiming = (value: number) => value.toString().padStart(2, '0');

export const createAssTimingFormatter = (unitsPerSecond: number) => {
  const unitsPerMinute = unitsPerSecond * 60;
  const unitsPerCentisecond = unitsPerSecond / 100;

  return (value: number) => {
    const minutes = Math.floor(value / unitsPerMinute);
    const seconds = Math.floor(
      (value - minutes * unitsPerMinute) / unitsPerSecond,
    );
    const remainingUnits =
      value - (minutes * unitsPerMinute + seconds * unitsPerSecond);
    const centiseconds = Math.floor(remainingUnits / unitsPerCentisecond);

    return `${padTiming(minutes)}:${padTiming(seconds)}.${padTiming(centiseconds)}`;
  };
};

interface ConstructCountdownOptions {
  firstTiming: number;
  startingNumber?: number;
  paddingTiming?: number;
  unitsPerSecond: number;
}

export const constructCountdown = ({
  firstTiming,
  startingNumber = 3,
  paddingTiming = 100,
  unitsPerSecond,
}: ConstructCountdownOptions): AssLine[] => {
  return Array.from({ length: startingNumber }, (_, index) => {
    const number = startingNumber - index;
    const countdownUnits = number * unitsPerSecond;

    return {
      start: firstTiming - countdownUnits - unitsPerSecond - paddingTiming,
      end: firstTiming - countdownUnits - paddingTiming,
      lyric: `{\\fad(300,300)}${number}`,
      style: 'Countdown',
    };
  });
};

interface AssLayoutOptions {
  fontSize: number;
  maxLinesOnScreen: number;
  screen?: LyricBuilderAssOptions['screen'];
}

interface ResolvedAssFontSizes {
  lyrics: number;
  subtitle: number;
}

export const resolveAssFontSizes = (
  fontSize?: LyricBuilderAssOptions['fontSize'],
): ResolvedAssFontSizes => {
  const lyrics = fontSize?.lyrics ?? 48;
  const subtitle =
    fontSize?.subtitle ?? Math.max(20, Math.round(lyrics * 0.55));

  return {
    lyrics,
    subtitle,
  };
};

export const createAssLayout = ({
  fontSize,
  maxLinesOnScreen,
  screen,
}: AssLayoutOptions) => {
  const { width, height } = screen || DEFAULT_SCREEN;
  const initialStartPos = height / maxLinesOnScreen;
  const positions = Array.from(
    { length: maxLinesOnScreen },
    (_, index) => initialStartPos + fontSize * index,
  );

  return {
    height,
    centerX: width / 2,
    positions,
  };
};

