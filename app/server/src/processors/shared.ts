interface DialogueLineOptions {
  start: number;
  end: number;
  lyric: string;
  style?: string;
  prefix?: string;
  formatTiming: (value: number) => string;
}

export const createDialogueLine = ({
  start,
  end,
  lyric,
  style = 'Default',
  prefix = '',
  formatTiming,
}: DialogueLineOptions) => {
  const startTiming = formatTiming(start);
  const endTiming = formatTiming(end);

  return `Dialogue: 0,0:${startTiming},0:${endTiming},${style},,0,0,0,,${prefix}${lyric}`;
};

interface DialogueWindow {
  start: number;
  end: number;
}

interface RenderAssChunkOptions<TLine extends { lyric: string }> {
  chunk: Array<TLine | undefined>;
  positions: number[];
  formatTiming: (value: number) => string;
  createPrefix: (args: { pos: number; isHighlighted: boolean }) => string;
  getWindow?: (
    line: TLine | undefined,
    index: number,
    chunk: Array<TLine | undefined>,
  ) => DialogueWindow | null;
  window?: DialogueWindow;
  highlightedIndex?: number;
}

export const renderAssChunk = <TLine extends { lyric: string }>({
  chunk,
  positions,
  formatTiming,
  createPrefix,
  getWindow,
  window,
  highlightedIndex,
}: RenderAssChunkOptions<TLine>) => {
  const renderedLines: string[] = [];

  for (let index = 0; index < chunk.length; index++) {
    const line = chunk[index];
    const pos = positions[index];
    const dialogueWindow = getWindow
      ? getWindow(line, index, chunk)
      : window || null;

    if (!dialogueWindow) {
      continue;
    }

    renderedLines.push(
      createDialogueLine({
        start: dialogueWindow.start,
        end: dialogueWindow.end,
        lyric: line?.lyric || '',
        prefix: createPrefix({
          pos,
          isHighlighted: index === highlightedIndex,
        }),
        formatTiming,
      }),
    );
  }

  return renderedLines;
};
